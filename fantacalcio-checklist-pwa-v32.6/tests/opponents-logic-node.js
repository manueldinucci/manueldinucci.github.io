const fs = require('fs');
const vm = require('vm');
const path = require('path');
const code = fs.readFileSync(path.join(__dirname,'..','auction-logic.js'),'utf8');
const ctx = { window:{} }; vm.createContext(ctx); vm.runInContext(code,ctx);
const F = ctx.window.FantaAuction;
const config = F.makeDefaultConfig({budgetInitial:500,minPrice:1,roster:{P:3,D:8,C:8,A:6}});
const luca={id:'l',nome:'Luca'}, marco={id:'m',nome:'Marco'}, me={id:'me',nome:'Manuel',isMe:true};
function p(key,manager,role,price){return {key,ruolo:role,preso:true,prezzo_acquisto:price,manager_id:manager.id,manager_acquirente:manager.nome};}
let players=[1,2,3,4,5].map((x,i)=>p('l'+x,luca,'C',10));
let s=F.computeManagerStats(luca,players,config);
if(s.roleRemaining.C!==3) throw new Error('precondizione C rimasti non valida');
players.push(p('mc',luca,'C',58));
s=F.computeManagerStats(luca,players,config);
if(s.roleRemaining.C!==2) throw new Error('TEST 1 fallito: C rimasti deve essere 2');
let seven=[1,2,3,4,5,6,7].map(x=>p('q'+x,luca,'C',1));
seven.push(p('last',luca,'C',5));
s=F.computeManagerStats(luca,seven,config);
if(s.roleRemaining.C!==0) throw new Error('TEST 2 fallito: ruolo non completo');
let demand=F.computeRoleDemand([me,luca,marco],[],config,'C');
if(demand.totalOpponents!==2 || demand.activeCount!==2 || demand.demand!==16) throw new Error('esclusione profilo Io fallita');
const need=F.roleNeedLevel(1,8); if(need.need!=='BASSO') throw new Error('need level fallito');
const strategic=F.strategicScore(F.computeManagerStats(luca,[],config),'C',config); if(!(strategic>0)) throw new Error('strategic score fallito');
console.log('Opponent intelligence tests passed');
